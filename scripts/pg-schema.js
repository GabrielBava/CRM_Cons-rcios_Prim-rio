#!/usr/bin/env node
'use strict';
/**
 * Gera server/pg/schema.sql (Postgres/Supabase) a partir do schema do CRM no SQLite (server/db.js): rode depois de
 * mudar tabelas, colunas ou índices — `npm run pg:schema`. O arquivo é idempotente: cria o que falta (tabelas,
 * colunas novas, índices e chaves estrangeiras) e não apaga nada, então serve tanto para o banco novo quanto para
 * atualizar um banco existente.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

function buildSchema() {
  const { DatabaseSync } = require('node:sqlite');
  const { initDb } = require('../server/db');
  const db = initDb(new DatabaseSync(':memory:'));
  const q = (id) => `"${id}"`;
  const typeOf = (decl) => (/INT/i.test(decl) ? 'bigint' : /REAL|FLOA|DOUB/i.test(decl) ? 'double precision' : /BLOB/i.test(decl) ? 'bytea' : /NUM|DEC/i.test(decl) ? 'numeric' : 'text');
  const tables = db.prepare("SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
  const out = { create: [], alter: [], index: [], fk: [] };
  for (const t of tables) {
    const cols = db.prepare(`PRAGMA table_info(${q(t.name)})`).all();
    const pk = cols.filter((c) => c.pk).sort((a, b) => a.pk - b.pk);
    const identity = pk.length === 1 && /INT/i.test(pk[0].type) ? pk[0].name : null;
    const colDef = (c, forAlter) => {
      let d = `${q(c.name)} ${typeOf(c.type)}`;
      if (c.name === identity) return `${d} GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
      if (c.dflt_value != null) d += ` DEFAULT ${c.dflt_value}`;
      // NOT NULL numa coluna nova de tabela com dados só é possível com valor padrão
      if (c.notnull && (!forAlter || c.dflt_value != null)) d += ' NOT NULL';
      return d;
    };
    const defs = cols.map((c) => colDef(c, false));
    if (pk.length && !identity) defs.push(`PRIMARY KEY (${pk.map((c) => q(c.name)).join(', ')})`);
    out.create.push(`CREATE TABLE IF NOT EXISTS ${q(t.name)} (\n  ${defs.join(',\n  ')}\n);`);
    for (const c of cols) if (!c.pk) out.alter.push(`ALTER TABLE ${q(t.name)} ADD COLUMN IF NOT EXISTS ${colDef(c, true)};`);
    // Índices: os explícitos (texto do SQLite) e os das restrições UNIQUE (automáticos)
    for (const ix of db.prepare(`PRAGMA index_list(${q(t.name)})`).all()) {
      if (ix.origin === 'pk') continue;
      const row = db.prepare("SELECT sql FROM sqlite_master WHERE type = 'index' AND name = ?").get(ix.name);
      if (row?.sql) {
        out.index.push(`${row.sql.replace(/^CREATE (UNIQUE )?INDEX (IF NOT EXISTS )?/i, (m, u) => `CREATE ${u || ''}INDEX IF NOT EXISTS `)};`);
      } else {
        const keys = db.prepare(`PRAGMA index_xinfo(${q(ix.name)})`).all().filter((k) => k.key && k.name);
        const expr = keys.map((k) => (k.coll === 'NOCASE' ? `lower(${q(k.name)})` : q(k.name))).join(', ');
        out.index.push(`CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX IF NOT EXISTS ${q(`${t.name}_${keys.map((k) => k.name).join('_')}_key`)} ON ${q(t.name)} (${expr});`);
      }
    }
    // Chaves estrangeiras (sem cascata, como no SQLite)
    const fks = new Map();
    for (const f of db.prepare(`PRAGMA foreign_key_list(${q(t.name)})`).all()) fks.set(f.id, [...(fks.get(f.id) || []), f]);
    for (const [id, parts] of fks) {
      const target = parts[0].table;
      const tcols = parts.map((p) => p.to || 'id');
      const name = `${t.name}_fk${id}`;
      const action = (a) => (a && a !== 'NO ACTION' ? ` ON DELETE ${a}` : '');
      out.fk.push(`DO $$ BEGIN ALTER TABLE ${q(t.name)} ADD CONSTRAINT ${q(name)} FOREIGN KEY (${parts.map((p) => q(p.from)).join(', ')}) REFERENCES ${q(target)} (${tcols.map(q).join(', ')})${action(parts[0].on_delete)}; EXCEPTION WHEN duplicate_object THEN NULL; END $$;`);
    }
  }
  const body = [
    '-- Schema do CRM Vero no Postgres (Supabase). Gerado por scripts/pg-schema.js a partir de server/db.js: não edite à mão.',
    '-- Idempotente: cria tabelas, colunas, índices e chaves estrangeiras que faltam; não apaga nada.',
    ...out.create, ...out.alter, ...out.index, ...out.fk,
  ].join('\n');
  const version = crypto.createHash('sha256').update(body).digest('hex').slice(0, 16);
  return { sql: `-- versão ${version}\n${body}\n`, version, tables: tables.length };
}

if (require.main === module) {
  const r = buildSchema();
  const file = path.join(__dirname, '..', 'server', 'pg', 'schema.sql');
  fs.writeFileSync(file, r.sql);
  console.log(`server/pg/schema.sql: ${r.tables} tabelas (versão ${r.version}).`);
}

module.exports = { buildSchema };
