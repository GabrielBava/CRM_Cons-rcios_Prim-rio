#!/usr/bin/env node
'use strict';
/**
 * Sincroniza uma cópia do banco do CRM (SQLite) com o Supabase (Postgres), num schema separado ("crm_teste").
 *
 *   # 1) Arquivo SQL para colar no SQL Editor do Supabase (ou rodar com psql)
 *   CRM_DB=data/crm.db node scripts/supabase-sync.js --arquivo supabase/crm_teste.sql
 *
 *   # 2) Envio direto pela API do Supabase (token pessoal: supabase.com › Account › Access Tokens)
 *   SUPABASE_ACCESS_TOKEN=sbp_... SUPABASE_PROJECT_REF=abcdefghijklmnop CRM_DB=data/crm.db node scripts/supabase-sync.js --enviar
 *
 * Opções: --schema <nome> (padrão crm_teste) · --sem-dados (só a estrutura) · --sem-anexos (sem o conteúdo dos arquivos).
 *
 * Cada sincronização recria o schema (DROP SCHEMA … CASCADE) e copia tudo de novo: é um retrato do CRM, não a base em uso.
 *  - Tipos: INTEGER → bigint (ou double/text se a coluna tiver outros valores), REAL → double precision, TEXT → text,
 *    BLOB → bytea. Chave primária "id" vira identity (o Supabase consegue inserir registros novos).
 *  - Índices simples e únicos são recriados; as chaves estrangeiras entram como NOT VALID (documentam as relações sem
 *    barrar a cópia).
 *  - Segurança: a tabela de sessões fica de fora; senhas, tokens, hashes e chaves cifradas vão como NULL; configurações
 *    com segredo (SMTP, Google) não são copiadas. RLS ligado em todas as tabelas, sem políticas: o schema não aparece
 *    na API pública do Supabase (só o SQL Editor e a chave service_role leem).
 */
const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
const flag = (k) => args.includes(`--${k}`);
const opt = (k, def) => {
  const i = args.indexOf(`--${k}`);
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : def;
};

const EXCLUDE_TABLES = new Set(['sessions']);
// Colunas com segredo: vão como NULL
const SECRET_COL = /(password_hash|_enc$|token_hash|verify_hash|^token$|public_token|simulator_token_hash)/i;
// Configurações com segredo (ou que guardam segredo dentro)
const SECRET_SETTING = /(_enc$|secret|smtp|token|password|api_key)/i;

const q = (id) => `"${String(id).replace(/"/g, '""')}"`;
const lit = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  if (typeof v === 'bigint') return v.toString();
  if (v instanceof Uint8Array) return `'\\x${Buffer.from(v).toString('hex')}'::bytea`;
  return `'${String(v).replace(/\u0000/g, '').replace(/'/g, "''")}'`;
};

/** Monta o SQL (lista de blocos) a partir do banco SQLite. */
function buildSql(db, { schema = 'crm_teste', data = true, files = true } = {}) {
  if (!/^[a-z_][a-z0-9_]{0,40}$/.test(schema)) throw new Error('Nome de schema inválido (use letras minúsculas, números e _).');
  const S = q(schema);
  const tables = db.prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all().map((r) => r.name).filter((t) => !EXCLUDE_TABLES.has(t));
  const blocks = [];
  const stamp = new Date().toISOString();
  blocks.push(`-- CRM Vero: cópia de teste (${stamp}). Gerado por scripts/supabase-sync.js.
DROP SCHEMA IF EXISTS ${S} CASCADE;
CREATE SCHEMA ${S};
COMMENT ON SCHEMA ${S} IS 'CRM Vero: cópia de teste sincronizada em ${stamp} (somente leitura para testes e BI)';`);
  const meta = [];
  for (const t of tables) {
    const cols = db.prepare(`PRAGMA table_info(${q(t)})`).all();
    const pk = cols.filter((c) => c.pk).sort((a, b) => a.pk - b.pk).map((c) => c.name);
    // Tipo de cada coluna pelo tipo declarado e pelos valores reais (o SQLite aceita valores de outros tipos)
    const types = {};
    for (const c of cols) {
      const decl = String(c.type || '').toUpperCase();
      let kind = /INT/.test(decl) ? 'int' : /REAL|FLOA|DOUB/.test(decl) ? 'real' : /BLOB/.test(decl) ? 'blob' : /NUM|DEC/.test(decl) ? 'num' : 'text';
      if (kind !== 'blob' && kind !== 'text') {
        const seen = db.prepare(`SELECT DISTINCT typeof(${q(c.name)}) AS t FROM ${q(t)}`).all().map((r) => r.t);
        if (seen.includes('text') || seen.includes('blob')) kind = 'text';
        else if (kind === 'int' && seen.includes('real')) kind = 'real';
      }
      types[c.name] = kind;
    }
    const pgType = { int: 'bigint', real: 'double precision', num: 'numeric', blob: 'bytea', text: 'text' };
    const identity = pk.length === 1 && types[pk[0]] === 'int' ? pk[0] : null;
    const defs = cols.map((c) => {
      let d = `${q(c.name)} ${pgType[types[c.name]]}`;
      if (c.name === identity) d += ' GENERATED BY DEFAULT AS IDENTITY';
      else if (c.notnull && !SECRET_COL.test(c.name)) d += ' NOT NULL';
      return d;
    });
    if (pk.length) defs.push(`PRIMARY KEY (${pk.map(q).join(', ')})`);
    blocks.push(`CREATE TABLE ${S}.${q(t)} (\n  ${defs.join(',\n  ')}\n);`);
    meta.push({ t, cols, types, identity });
  }
  // Dados
  let rowsTotal = 0;
  if (data) {
    for (const { t, cols, types } of meta) {
      const names = cols.map((c) => c.name);
      let rows = db.prepare(`SELECT * FROM ${q(t)}`).all();
      if (t === 'settings') rows = rows.filter((r) => !SECRET_SETTING.test(String(r.key)));
      if (!rows.length) continue;
      rowsTotal += rows.length;
      const val = (r, n) => {
        if (SECRET_COL.test(n)) return 'NULL';
        if (types[n] === 'blob' && !files) return 'NULL';
        return lit(r[n]);
      };
      for (let i = 0; i < rows.length; i += 200) {
        const chunk = rows.slice(i, i + 200);
        blocks.push(`INSERT INTO ${S}.${q(t)} (${names.map(q).join(', ')}) OVERRIDING SYSTEM VALUE VALUES\n${chunk.map((r) => `(${names.map((n) => val(r, n)).join(', ')})`).join(',\n')};`);
      }
    }
    // Identity continua do maior id copiado
    for (const { t, identity } of meta) {
      if (identity) blocks.push(`SELECT setval(pg_get_serial_sequence('${schema}.${q(t).replace(/'/g, "''")}', '${identity}'), COALESCE((SELECT MAX(${q(identity)}) FROM ${S}.${q(t)}), 0) + 1, false);`);
    }
  }
  // Índices (simples e únicos, sem os parciais e de expressão) e chaves estrangeiras (NOT VALID)
  const pkOf = new Map(meta.map((m) => [m.t, m.cols.filter((c) => c.pk).map((c) => c.name)]));
  for (const { t } of meta) {
    for (const ix of db.prepare(`PRAGMA index_list(${q(t)})`).all()) {
      if (ix.origin === 'pk' || ix.partial) continue;
      const icols = db.prepare(`PRAGMA index_info(${q(ix.name)})`).all();
      if (!icols.length || icols.some((c) => c.name == null)) continue;
      blocks.push(`CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX ${q(`${t}__${icols.map((c) => c.name).join('_')}`.slice(0, 63))} ON ${S}.${q(t)} (${icols.map((c) => q(c.name)).join(', ')});`);
    }
    const fks = db.prepare(`PRAGMA foreign_key_list(${q(t)})`).all();
    const byId = new Map();
    for (const f of fks) byId.set(f.id, [...(byId.get(f.id) || []), f]);
    for (const [, parts] of byId) {
      const target = parts[0].table;
      if (!pkOf.has(target)) continue;
      const to = parts.map((p) => p.to || pkOf.get(target)[0]);
      // Só para chave primária de uma coluna (o Postgres exige destino único)
      if (to.length !== 1 || pkOf.get(target).length !== 1 || to[0] !== pkOf.get(target)[0]) continue;
      blocks.push(`ALTER TABLE ${S}.${q(t)} ADD FOREIGN KEY (${q(parts[0].from)}) REFERENCES ${S}.${q(target)} (${q(to[0])}) NOT VALID;`);
    }
  }
  // Fora da API pública: RLS ligado sem políticas
  blocks.push(meta.map(({ t }) => `ALTER TABLE ${S}.${q(t)} ENABLE ROW LEVEL SECURITY;`).join('\n'));
  blocks.push(`DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN EXECUTE 'REVOKE ALL ON SCHEMA ${schema} FROM anon, authenticated'; END IF; END $$;`);
  return { blocks, tables: meta.length, rows: rowsTotal };
}

/** Envia os blocos pela API de gerenciamento do Supabase (POST /v1/projects/{ref}/database/query), em lotes. */
async function sendToSupabase(blocks, { token, ref, maxBytes = 400000 } = {}) {
  if (!token || !ref) throw new Error('Defina SUPABASE_ACCESS_TOKEN e SUPABASE_PROJECT_REF.');
  const batches = [];
  let cur = '';
  for (const b of blocks) {
    if (cur && cur.length + b.length > maxBytes) {
      batches.push(cur);
      cur = '';
    }
    cur += `${b}\n`;
  }
  if (cur) batches.push(cur);
  for (let i = 0; i < batches.length; i++) {
    const r = await fetch(`https://api.supabase.com/v1/projects/${encodeURIComponent(ref)}/database/query`, {
      method: 'POST',
      headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({ query: batches[i] }),
    });
    if (!r.ok) throw new Error(`Supabase respondeu ${r.status} no lote ${i + 1}/${batches.length}: ${(await r.text()).slice(0, 400)}`);
    process.stdout.write(`\rEnviado ${i + 1}/${batches.length}`);
  }
  process.stdout.write('\n');
  return batches.length;
}

async function main() {
  // Token e projeto podem vir do config.env (SUPABASE_ACCESS_TOKEN, SUPABASE_PROJECT_REF), como as outras chaves
  require('../server/env').loadConfigEnv();
  const { DatabaseSync } = require('node:sqlite');
  const dbFile = process.env.CRM_DB || path.join(__dirname, '..', 'data', 'crm.db');
  if (!fs.existsSync(dbFile)) throw new Error(`Banco não encontrado: ${dbFile} (defina CRM_DB).`);
  const db = new DatabaseSync(dbFile, { readOnly: true });
  const schema = opt('schema', 'crm_teste');
  const out = buildSql(db, { schema, data: !flag('sem-dados'), files: !flag('sem-anexos') });
  const file = opt('arquivo');
  if (file) {
    fs.mkdirSync(path.dirname(path.resolve(file)), { recursive: true });
    fs.writeFileSync(file, `BEGIN;\n${out.blocks.join('\n')}\nCOMMIT;\n`);
    console.log(`Arquivo ${file}: ${out.tables} tabelas, ${out.rows} registros no schema ${schema}.`);
  }
  if (flag('enviar')) {
    const n = await sendToSupabase(out.blocks, { token: process.env.SUPABASE_ACCESS_TOKEN, ref: process.env.SUPABASE_PROJECT_REF });
    console.log(`Supabase sincronizado: ${out.tables} tabelas, ${out.rows} registros no schema ${schema} (${n} lote(s)).`);
  }
  if (!file && !flag('enviar')) console.log('Informe --arquivo <saida.sql> e/ou --enviar.');
}

if (require.main === module) {
  main().catch((e) => {
    console.error(e.message);
    process.exit(1);
  });
}

module.exports = { buildSql, sendToSupabase };
